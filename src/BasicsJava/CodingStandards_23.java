package BasicsJava;

public class CodingStandards_23 {
    public static void main(String[] args) {
        System.out.println("This class explains coding standards in Java");
        System.out.println("1. Class Naming Rule" +
                " Use: PascalCase - " +
                "Meaning:\n" +
                "First letter of every word = Capital");

        System.out.println();

        System.out.println("2. Method Naming Rule" +
                " Use: camelCase -" +
                " Meaning:\n" +
                "first word small, " +
                "next words Capital");

        System.out.println();

        System.out.println("3. Variable Naming Rule" +
                " Use: camelCase" +
                " Same like method naming");

        System.out.println();

        System.out.println("4. Constant Naming Rule" +
                " Use: UPPER_CASE");

        System.out.println();

        System.out.println("5. Package Naming Rule" +
                " Use: lower case only");

        System.out.println();

        System.out.println("6. Indentation" +
                " Always use proper spacing for clean and readable coding");

        System.out.println();

        System.out.println("Coding standards improve \n" +
                "* Readability\n" +
                "* Maintainability\n" +
                "* Teamwork\n" +
                "* Debugging\n" +
                "* Professionalism");
    }
}
