/**
 * escape sequences -
 * special characters cannot be written directly inside strings so we need formatting control.
 */

package BasicsJava;

public class EscapeSequences_24 {
    public static void main(String[] args) {
        System.out.println("Hello\nWold!"); //new line
        System.out.println("Java\tRocks");//tab
        System.out.println("He said \"Hi\" \'How are you\'");//double and single quote
        System.out.println("Character is 'H'");
        System.out.println("C:\\users\\Athulya");//path
        System.out.println("abc\bdef");//for backspace
    }
}
